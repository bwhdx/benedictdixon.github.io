// Concatenate the compiled .js files into a single bundle.js so the browser
// only fetches one app script. Order matters: later files use globals that
// earlier ones define (window.SITE, window.ScrollMotion, window.App...).
//
// The bundle opens with window.SITE, the facts the build writes once for the
// whole site (tools/site-data.cjs): the cover line, the privacy note, and
// each essay's date, reading time and cover.

const fs = require('fs');
const path = require('path');
const { siteGlobals } = require('./site-globals.cjs');

const ROOT = path.join(__dirname, '..');

// The app, in load order; boot.js last, since it starts the app.
const APP = [
  'scroll-motion.js',
  'portrait-renderers.js',
  'site-content.js',
  'portfolio-app.js',
];
const ORDER = [...APP, 'boot.js'];

function build() {
  const banner = `/* Bundle of window.SITE, ${ORDER.join(', ')}. Generated by tools/bundle.cjs */\n`;
  const site = `window.SITE = ${JSON.stringify(siteGlobals())};\n`;
  const out = banner + site + ORDER
    .map((f) => {
      const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
      return `\n/* ── ${f} ────────────────────────────────────────── */\n${src}`;
    })
    .join('\n');
  fs.writeFileSync(path.join(ROOT, 'bundle.js'), out);
  console.log(`Wrote bundle.js (${(out.length / 1024).toFixed(1)} KB, ${ORDER.length} files)`);
}

if (require.main === module) build();
module.exports = { APP };
